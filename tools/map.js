// Writes docs/MAP.md: every app file with what it holds, its sections, its top-level functions and constants with line
// numbers, and which files use each Firestore document. Grep the map instead of reading code to find where something lives.
// Usage: node tools/map.js          (rewrite docs/MAP.md)
//        node tools/map.js --check  (exit 1 if docs/MAP.md is out of date; used by tools/check.js)
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const files = [...fs.readFileSync(path.join(root, 'index.html'), 'utf8').matchAll(/<script src="(app\/[^"]+)"/g)].map(m => m[1]);
const mealFiles = [...fs.readFileSync(path.join(root, 'meals', 'index.html'), 'utf8').matchAll(/<script src="(js\/[^"]+)"/g)].map(m => 'meals/' + m[1]);
const out = ['# Afloat code map', '', 'Generated by `node tools/map.js` (run by `node tools/check.js`). Do not edit by hand.', '',
  'Files load in this order and share one scope, so a name defined in any file can be used in any other once the app has started.', ''];
const docs = {};
for (const f of [...files, ...mealFiles]) {
  if (f === mealFiles[0]) out.push('# Meals (meals/index.html, its own page in a frame; its files share their own scope)', '');
  const text = fs.readFileSync(path.join(root, f), 'utf8'), lines = text.split('\n');
  const what = (lines[0].match(/· (?:app\/|meals\/js\/)?[\w.-]+ · (.*?)\.?$/) || [, ''])[1];
  out.push(`## ${f} (${lines.length} lines, ${Math.round(text.length / 1024)} KB)`, '', what, '');
  const secs = [], defs = [];
  lines.forEach((l, i) => {
    const s = l.match(/^\/\*-* ?-{3,} ?(.*?)(?: -{3,}.*)?(?:\*\/)?$/);
    if (s && i > 1) secs.push(`${i + 1} ${s[1].replace(/\s*\*\/$/, '').replace(/ -+$/, '').slice(0, 80)}`);
    const d = l.match(/^(?:async\s+)?function\s*\*?\s*([\w$]+)|^(?:const|let|var)\s+([\w$]+)/);
    if (d) defs.push(`${d[1] || d[2]}:${i + 1}`);
    if (!f.startsWith('meals/')) for (const m of l.matchAll(/\b(?:H|saveHome|useOf)\('(\w+)'|['`]home\/(\w+)/g)) (docs['home/' + (m[1] || m[2])] ||= new Set()).add(path.basename(f));
  });
  if (secs.length) out.push('Sections: ' + secs.join(' · '), '');
  out.push('Defines: ' + defs.join(' '), '');
}
out.push('## Firestore documents (apps/afloat/…) and the files that use them', '');
for (const k of Object.keys(docs).sort()) out.push(`- ${k}: ${[...docs[k]].join(', ')}`);
out.push('', 'Also: days/<date>, weeks/<date>, months/<yyyy-mm>, plans/<date>, events/*, usage/*, notify/<uid> (see store.js and reminders.js).', '');
const md = out.join('\n'), file = path.join(root, 'docs', 'MAP.md');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (cur !== md) { console.log('docs/MAP.md is out of date: run node tools/map.js'); process.exit(1); }
} else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, md); console.log('docs/MAP.md written'); }
